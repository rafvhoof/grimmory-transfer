#!/usr/bin/env bash
set -Eeuo pipefail
source "$(dirname "$0")/common.sh"
preflight
assert_mounts
[[ $# -eq 1 ]] || die "Usage: scripts/import.sh /path/to/grimmory-backup-directory"
SOURCE="$(cd "$1" && pwd)"
[[ "$(state "$DB_CONTAINER")" == true ]] || die 'Start only destination MariaDB first'
[[ "$(state "$APP_CONTAINER")" == false ]] || die 'Stop destination Grimmory first (docker compose stop grimmory)'
[[ "${CONFIRM_REPLACE:-}" == 'YES' ]] || die 'Explicit approval required: set CONFIRM_REPLACE=YES after reading README and making a destination backup'
for file in database.sql app-data.tar.gz books.tar.gz bookdrop.tar.gz manifest.txt SHA256SUMS; do
  [[ -f "$SOURCE/$file" ]] || die "Missing $file"
done
sha_check "$SOURCE"
grep -Fxq 'format=grimmory-transfer-v1' "$SOURCE/manifest.txt" || die 'Unsupported backup format'
# Fail closed if app volumes are not empty. Intentional destructive replacement must be performed manually.
for path in /app/data /books /bookdrop; do
  docker run --rm --volumes-from "$APP_CONTAINER":ro "$IMAGE" sh -c \
    'test -z "$(ls -A "$1")"' sh "$path" || die "Destination $path is not empty; do not overwrite. See README."
done
# Also reject existing destination database tables.
TABLES="$(docker exec -e MYSQL_PWD="$DB_PASSWORD" "$DB_CONTAINER" mariadb --batch --skip-column-names \
  --user="$DB_USER" --database="$DB_NAME" --execute='SHOW TABLES;' | wc -l)"
[[ "$TABLES" -eq 0 ]] || die "Destination database contains $TABLES tables; import only into a fresh empty DB."
# Archive extraction is confined to each fixed mount; archives are generated by export.sh.
for entry in 'app-data:/app/data' 'books:/books' 'bookdrop:/bookdrop'; do
  name="${entry%%:*}" path="${entry#*:}"
  echo "Restoring $path"
  docker run --rm --volumes-from "$APP_CONTAINER":rw -v "$SOURCE:/backup:ro" "$IMAGE" \
    tar -C "$path" -xzf "/backup/$name.tar.gz"
done
echo 'Restoring MariaDB...'
docker exec -i -e MYSQL_PWD="$DB_PASSWORD" "$DB_CONTAINER" mariadb \
  --user="$DB_USER" --database="$DB_NAME" < "$SOURCE/database.sql"
echo 'Import complete. Start destination Grimmory, review permissions, library paths, logs and reading progress.'
