#!/usr/bin/env bash
set -Eeuo pipefail
source "$(dirname "$0")/common.sh"
source "$ROOT/scripts/nextcloud.sh"
trap nextcloud_cleanup EXIT
[[ $# -le 1 ]] || die 'Usage: scripts/import.sh [/path/to/local-backup-directory] (without a path, download from Nextcloud)'
preflight
assert_mounts
reuse_books_setting
[[ "$(state "$DB_CONTAINER")" == true ]] || die 'Start only destination MariaDB first'
[[ "$(state "$APP_CONTAINER")" == false ]] || die 'Stop destination Grimmory first (docker compose stop grimmory)'
[[ "${CONFIRM_REPLACE:-}" == 'YES' ]] || die 'Explicit approval required: set CONFIRM_REPLACE=YES after reading README and making a destination backup'
if [[ $# -eq 1 ]]; then
  SOURCE="$(cd "$1" && pwd)"
else
  nextcloud_init
  MIGRATION_ID="$(resolve_migration_id)"
  SOURCE="$BACKUP_DIR/$MIGRATION_ID"
  download_bundle "$MIGRATION_ID" "$SOURCE"
  SOURCE="$(cd "$SOURCE" && pwd)"
fi
verify_bundle "$SOURCE"
if [[ "$BOOKS_MODE" == shared ]]; then
  [[ "$REUSE_EXISTING_BOOKS" == 1 ]] || die 'This bundle reuses existing /books; set REUSE_EXISTING_BOOKS=1 on the destination after mounting the same Synology library'
  check_shared_books destination
else
  [[ "$REUSE_EXISTING_BOOKS" == 0 ]] || die 'This bundle contains books.tar.gz; set REUSE_EXISTING_BOOKS=0 on the destination'
fi
SOURCE_IMAGE="$(metadata_value "$SOURCE" source_app_image)"
TARGET_IMAGE="$(docker inspect --format '{{.Config.Image}}' "$APP_CONTAINER")"
SOURCE_IMAGE_ID="$(metadata_value "$SOURCE" source_app_image_id)"
[[ -n "$SOURCE_IMAGE" ]] || die 'Backup manifest has no source_app_image'
if [[ -n "$SOURCE_IMAGE_ID" ]]; then
  # A source tagged latest and a target pinned by digest can be identical images.
  [[ "$SOURCE_IMAGE_ID" == "$(docker inspect --format '{{.Image}}' "$APP_CONTAINER")" ]] || die "Image mismatch: source is $SOURCE_IMAGE; target is $TARGET_IMAGE with different contents. Pin the running source image digest before importing."
else
  [[ "$SOURCE_IMAGE" == "$TARGET_IMAGE" ]] || die "Image mismatch: source is $SOURCE_IMAGE; target is $TARGET_IMAGE. This legacy bundle has no image ID; use the same reference or make a new export."
fi
SOURCE_DB_NAME="$(metadata_value "$SOURCE" db_name)"
[[ -z "$SOURCE_DB_NAME" || "$SOURCE_DB_NAME" == "$DB_NAME" ]] || die "Database name mismatch: source is $SOURCE_DB_NAME; target is $DB_NAME. Preserve the source database name when modernizing Compose."
# Fail closed if any mount we will restore is not empty. Shared /books is reused.
for path in /app/data /books /bookdrop; do
  [[ "$BOOKS_MODE" != shared || "$path" != /books ]] || continue
  docker run --rm --volumes-from "$APP_CONTAINER":ro "$IMAGE" sh -c \
    'test -z "$(ls -A "$1")"' sh "$path" || die "Destination $path is not empty; do not overwrite. See README."
done
# Also reject existing destination database tables.
TABLES="$(docker exec -e MYSQL_PWD="$DB_PASSWORD" "$DB_CONTAINER" mariadb --batch --skip-column-names \
  --user="$DB_USER" --database="$DB_NAME" --execute='SHOW TABLES;' | wc -l)"
[[ "$TABLES" -eq 0 ]] || die "Destination database contains $TABLES tables; import only into a fresh empty DB."
# Archive extraction is confined to each fixed mount; archives are generated by export.sh.
for entry in 'app-data:/app/data' 'books:/books' 'bookdrop:/bookdrop'; do
  name="${entry%%:*}" path="${entry#*:}"
  [[ "$BOOKS_MODE" != shared || "$path" != /books ]] || continue
  echo "Restoring $path"
  docker run --rm --volumes-from "$APP_CONTAINER":rw -v "$SOURCE:/backup:ro" "$IMAGE" \
    tar -C "$path" -xzf "/backup/$name.tar.gz"
done
echo 'Restoring MariaDB...'
docker exec -i -e MYSQL_PWD="$DB_PASSWORD" "$DB_CONTAINER" mariadb \
  --user="$DB_USER" --database="$DB_NAME" < "$SOURCE/database.sql"
echo 'Import complete. Start destination Grimmory, review permissions, library paths, logs and reading progress.'
